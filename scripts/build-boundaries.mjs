#!/usr/bin/env node
// Builds src/server/data/india-boundaries.ts from geoBoundaries (gbOpen, pinned commit):
//   ADM1 states/UTs  - DataMeet India community / ECI, CC BY 2.5 IN
//   ADM2 districts   - Pathways Data / lgdirectory.gov.in (2021), ODbL 1.0
// Usage: node scripts/build-boundaries.mjs
import { writeFile, mkdir } from "node:fs/promises";
import mapshaper from "mapshaper";
import { distanceToAreaKm, inArea } from "../src/lib/boundary.ts";

const BASE = "https://github.com/wmgeolab/geoBoundaries/raw/9469f09/releaseData/gbOpen/IND";
// States are checked with a 2 km tolerance; district matching is advisory, so it can be coarser.
const STATE_INTERVAL_M = 250;
const DISTRICT_INTERVAL_M = 700;

async function load(level) {
  const res = await fetch(`${BASE}/${level}/geoBoundaries-IND-${level}_simplified.geojson`);
  if (!res.ok) throw new Error(`${level}: HTTP ${res.status}`);
  return res.text();
}

async function simplify(geojson, interval, extra = "") {
  const out = await mapshaper.applyCommands(
    `-i in.json -simplify interval=${interval} keep-shapes -clean ${extra} -o out.json format=geojson precision=0.001`,
    { "in.json": geojson }
  );
  return JSON.parse(out["out.json"]);
}

const round = (n) => Math.round(n * 1e3) / 1e3;

function toArea(geometry) {
  const polys = geometry.type === "Polygon" ? [geometry.coordinates] : geometry.type === "MultiPolygon" ? geometry.coordinates : [];
  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
  const flat = polys.map((poly) =>
    poly.map((ring) => {
      const r = [];
      for (const [x, y] of ring) {
        r.push(round(x), round(y));
        minX = Math.min(minX, x); minY = Math.min(minY, y); maxX = Math.max(maxX, x); maxY = Math.max(maxY, y);
      }
      return r;
    })
  );
  return { bbox: [round(minX), round(minY), round(maxX), round(maxY)], polys: flat };
}

const [adm1, adm2] = await Promise.all([load("ADM1"), load("ADM2")]);
const states = (await simplify(adm1, STATE_INTERVAL_M)).features.map((f) => ({
  iso: f.properties.shapeISO.replace(/^IN-/, ""),
  name: f.properties.shapeName,
  ...toArea(f.geometry),
}));
// Each district is assigned to the state containing an interior point of it.
const districtFeatures = (await simplify(adm2, DISTRICT_INTERVAL_M, "-each 'px=this.innerX, py=this.innerY'")).features;
const unplaced = [];
const districts = districtFeatures.map((f) => {
  const { px, py } = f.properties;
  let state = states.find((s) => inArea(px, py, s));
  if (!state) {
    unplaced.push(f.properties.shapeName);
    state = states.reduce((a, b) => (distanceToAreaKm(px, py, a) <= distanceToAreaKm(px, py, b) ? a : b));
  }
  return { name: f.properties.shapeName, iso: state?.iso ?? null, ...toArea(f.geometry) };
});

const data = {
  source: "geoBoundaries gbOpen IND ADM1 (CC BY 2.5 IN, DataMeet/ECI) and ADM2 (ODbL 1.0, Pathways Data/LGD 2021), simplified",
  states,
  districts,
};
await mkdir("src/server/data", { recursive: true });
const body = JSON.stringify(data);
await writeFile(
  "src/server/data/india-boundaries.ts",
  `// Generated by scripts/build-boundaries.mjs - do not edit.\n// ${data.source}\nimport type { BoundaryData } from "@/lib/boundary";\n\nexport const INDIA_BOUNDARIES: BoundaryData = JSON.parse(${JSON.stringify(body)});\n`
);
console.log(`${states.length} states, ${districts.length} districts, ${(body.length / 1e6).toFixed(2)} MB`);
if (unplaced.length) console.log(`Assigned to the nearest state: ${unplaced.join(", ")}`);
